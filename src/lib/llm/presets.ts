export function findPresetModelSpec(
  presetKey: PresetProviderKey,
  modelId: string,
): PresetModelSpec | undefined {
  if (presetKey === 'custom') return undefined;
  return PRESET_PROVIDERS[presetKey].models.find((m) => m.id === modelId);
}
