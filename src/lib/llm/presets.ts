export function buildBailianBaseUrl(
  workspaceId: string,
  region: string,
  useLegacyEndpoint = false,
): string {
  if (useLegacyEndpoint) {
    return region.startsWith('cn-')
      ? 'https://dashscope.aliyuncs.com/compatible-mode/v1'
      : 'https://dashscope-intl.aliyuncs.com/compatible-mode/v1';
  }
  const cleanWs = workspaceId.trim();
  const cleanRegion = region.trim() || 'cn-beijing';
  if (!cleanWs) {
    return '';
  }
  return `https://${cleanWs}.${cleanRegion}.maas.aliyuncs.com/compatible-mode/v1`;
}

