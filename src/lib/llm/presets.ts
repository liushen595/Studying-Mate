export function createInitialProviderProfiles(): ProviderProfile[] {
  const keys: Array<Exclude<PresetProviderKey, 'custom'>> = [
    'deepseek',
    'dashscope',
    'openai',
    'anthropic',
    'gemini',
  ];

  return keys.map((key) => {
    const def = PRESET_PROVIDERS[key];
    const defaultModel = def.models[0];
    return {
      id: key,
      presetKey: key,
      name: def.name,
      protocol: def.protocol,
      baseUrl: def.defaultBaseUrl,
      workspaceMeta:
        key === 'dashscope'
          ? { workspaceId: '', region: 'cn-beijing', useLegacyEndpoint: false }
          : undefined,
      apiKey: '',
      modelId: defaultModel.id,
      capabilities: { ...defaultModel.capabilities },
      params: createDefaultParamsFromModel(defaultModel),
    };
  });
}

