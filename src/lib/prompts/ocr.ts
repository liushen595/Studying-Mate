export function buildOcrUserPrompt(pageStart: number, pageEnd: number, totalPages: number): string {
  const reminder =
    '特别留意：①红笔方框标出的生词用 {{}} 包裹；②红笔订正后的最终答案用 [ANSWER: 题号=选项] 标出；③Part C 翻译题中被印刷下划线标出的待译句子必须完整用 <u>(46) ...</u> 包裹起止范围；④Section III 写作若含图画或图表，用 [图画/图表信息：...] 客观抄录画面与数据。仅做 OCR 转录，不要做任何翻译、解题或写范文。';
  if (totalPages === 1) {
    return `请按规则忠实转录这张考研英语试卷图片（${reminder}）。`;
  }
  return `以下是整套试卷的第 ${pageStart} 至第 ${pageEnd} 页（共 ${totalPages} 页）。请按页码顺序连续、忠实转录这些图片内容（${reminder}）。`;
}
